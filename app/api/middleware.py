"""Request hardening that sits in front of every route.

Three checks, each cheap enough to run on health probes too where relevant:

1. **Security headers** on every response.
2. **Origin allowlist** when ``ALLOWED_ORIGINS`` is set — browsers send Origin
   on cross-site calls; rejecting an unexpected one stops a page the operator
   did not authorise from driving the API with a visitor's token.
3. **Rate limiting** on chat and session issuance.
4. **Session auth** on chat when ``SESSION_TOKEN_SECRET`` is configured.

Local development with an empty secret and empty origin list skips (2) and
(4), which is the only way the interactive docs stay usable without a login
ceremony. Production must set both.
"""

from __future__ import annotations

from collections.abc import Awaitable, Callable

import structlog
from fastapi import FastAPI, Request, Response
from fastapi.responses import JSONResponse

from app.api.rate_limit import RateLimiter, RateLimitExceededError
from app.api.session import SessionClaims, SessionError, verify_token
from app.core.config import Settings

__all__ = ["install_security"]

logger = structlog.get_logger(__name__)

_AUTHENTICATED = ("/api/chat", "/api/catalog")
"""Paths that need a bearer token.

The catalogue is here because it is the business's own account of what it does
and does not cover, priced work included — internal by nature, even though it
only reads. Health stays open so an uptime probe can reach it, and it says
nothing a competitor could not guess."""

# Paths that never require a session and never consume rate-limit budget.
_PUBLIC = frozenset({"/", "/api/health", "/docs", "/openapi.json", "/redoc"})


def install_security(application: FastAPI, settings: Settings) -> None:
    limiter = RateLimiter(
        limit=settings.rate_limit_requests,
        window_seconds=settings.rate_limit_window_seconds,
    )
    application.state.rate_limiter = limiter
    require_auth = bool(settings.session_token_secret)

    @application.middleware("http")
    async def security(
        request: Request, call_next: Callable[[Request], Awaitable[Response]]
    ) -> Response:
        path = request.url.path

        if denied := _check_origin(request, settings):
            return denied

        # A CORS preflight asks whether the real request would be allowed. It
        # is generated by the browser, never carries credentials, and does no
        # work — so neither gate below applies to it.
        #
        # Authenticating it is the trap. This middleware runs outside the CORS
        # middleware, so an OPTIONS to /api/chat reached the bearer-token check
        # with no Authorization header and was refused 401. Signing in still
        # worked, because /api/session is not behind auth; every message after
        # it failed. Cross-origin only, so the page this service serves itself
        # never showed it.
        #
        # Rate limiting it is merely wasteful: a POST carrying an
        # Authorization header always costs a preflight too, which would have
        # spent the caller's allowance at twice the rate for half the requests.
        #
        # The origin check above still applies, and the real request that
        # follows is authenticated exactly as before.
        if request.method != "OPTIONS":
            if _should_rate_limit(path) and (limited := _check_rate_limit(request, limiter)):
                return limited

            if require_auth and path.startswith(_AUTHENTICATED):
                try:
                    request.state.session = _authenticate(
                        request, settings.session_token_secret
                    )
                except SessionError as exc:
                    logger.info("auth.rejected", reason=str(exc), path=path)
                    return JSONResponse(status_code=401, content={"detail": "Unauthorised."})

        response = await call_next(request)
        _apply_security_headers(response, path=path)
        return response


def _should_rate_limit(path: str) -> bool:
    """Chat and session issuance only. Static assets and health stay free."""
    if path in _PUBLIC or path.startswith("/widget"):
        return False
    return path.startswith("/api/")


def _check_origin(request: Request, settings: Settings) -> JSONResponse | None:
    """Reject a present-but-unknown Origin. Absent Origin is allowed.

    Non-browser clients often omit the header. Blocking those would break every
    curl-based check. The dangerous case is a browser on a foreign site sending
    a visitor's token, and that always includes Origin.
    """
    if not settings.origins:
        return None

    origin = request.headers.get("origin")
    if origin is None:
        return None

    # Settings.origins is already lowercased and stripped of trailing slashes,
    # so only the incoming header needs normalising to match it.
    normalised = origin.rstrip("/").casefold()
    if normalised in set(settings.origins):
        return None

    if _is_same_origin(request, normalised):
        return None

    logger.info("origin.rejected", origin=origin)
    return JSONResponse(status_code=403, content={"detail": "Origin not allowed."})


def _is_same_origin(request: Request, origin: str) -> bool:
    """Whether the Origin names the very host this request was addressed to.

    The service must never refuse its own page. A module script is fetched in
    CORS mode, so the chat page this service serves at ``/`` sends its own
    origin with the request for its own bundle — and once ALLOWED_ORIGINS named
    only the Webflow site, the service answered 403 to itself and the page
    loaded to a blank screen. The allowlist exists to admit *other* origins;
    same-origin was never its business.

    Compared by host rather than by whole origin because Cloud Run terminates
    TLS. The page the browser loaded is https, the request reaches the app as
    http, and the two schemes would never match.

    This concedes nothing. A browser sets Origin itself and cannot be made to
    lie about it, and any client that can forge the header could simply omit
    it, which is already allowed. The bearer token is what actually guards a
    turn.
    """
    host = request.headers.get("host", "").strip().casefold()
    if not host:
        return False
    return origin.partition("://")[2] == host


def _check_rate_limit(request: Request, limiter: RateLimiter) -> JSONResponse | None:
    key = _client_key(request)
    try:
        limiter.check(key)
    except RateLimitExceededError as exc:
        logger.info("rate_limit.exceeded", key=key, retry_after=exc.retry_after)
        return JSONResponse(
            status_code=429,
            content={"detail": "Too many requests. Try again shortly."},
            headers={"Retry-After": str(exc.retry_after)},
        )
    return None


def _authenticate(request: Request, secret: str) -> SessionClaims:
    header = request.headers.get("authorization", "")
    scheme, _, token = header.partition(" ")
    if scheme.lower() != "bearer" or not token:
        raise SessionError("Missing bearer token.")
    return verify_token(token.strip(), secret)


def _client_key(request: Request) -> str:
    """Best-effort caller identity for the rate limiter.

    Cloud Run puts the real client in ``X-Forwarded-For``. Trusting it is
    acceptable here because the load balancer is the only thing that can set
    it; a direct caller without that header falls back to the peer address.
    """
    forwarded = request.headers.get("x-forwarded-for")
    if forwarded:
        return forwarded.split(",", 1)[0].strip()
    if request.client is not None:
        return request.client.host
    return "unknown"


def _apply_security_headers(response: Response, *, path: str) -> None:
    response.headers.setdefault("X-Content-Type-Options", "nosniff")
    response.headers.setdefault("Referrer-Policy", "strict-origin-when-cross-origin")
    response.headers.setdefault("X-Frame-Options", "DENY")

    # API responses carry no executable content, so the strictest policy is safe.
    # The internal page needs its own script, fonts, and same-origin fetches.
    # style-src allows 'unsafe-inline' because <acme-chat> injects its stylesheet
    # into the shadow root as a <style> element (there is no separate CSS file).
    if path.startswith("/api/"):
        policy = "frame-ancestors 'none'; default-src 'none'"
    else:
        policy = (
            "default-src 'self'; "
            "script-src 'self'; "
            "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; "
            "font-src 'self' https://fonts.gstatic.com; "
            "connect-src 'self'; "
            "img-src 'self' data:; "
            "frame-ancestors 'none'"
        )
    response.headers.setdefault("Content-Security-Policy", policy)
