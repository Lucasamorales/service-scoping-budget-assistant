"""Rewrite the offline rate card from the live spreadsheet.

    python -m scripts.refresh_rate_card
    python -m scripts.refresh_rate_card --check

``fixtures/quote/rate_card.json`` is what prices services when no spreadsheet
is configured — local runs, the test suite, the eval harness. Production reads
the sheet directly, so the fixture only matters when it *disagrees* with the
sheet, and then it matters a great deal: a test suite that passes against stale
numbers is worse than no test suite.

That is not hypothetical. The fixture used to be maintained by hand and drifted
until it mapped Merch to Tier 1 where the sheet said Tier 3 — a £250 error,
carrying a note admitting the value had been guessed. Fifteen further services
were simply missing. This script exists so refreshing is one command instead of
an editing job nobody remembers to do.

``--check`` reports drift without writing and exits non-zero when it finds any.
It needs Sheets credentials, which CI does not carry, so this is a thing to run
before a release rather than a gate that runs itself.
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Mapping

from app.core.config import get_settings
from app.knowledge.catalog import load_catalog
from app.knowledge.manifest import Manifest
from app.store.quote import (
    _load_pricing_tiers_from_sheets,
    _load_service_tiers_from_sheets,
)

NOTE = (
    "Generated by scripts/refresh_rate_card.py from the Scope and Pricing_tiers "
    "tabs. Offline fallback only; production reads the sheet. Do not hand-edit — "
    "re-run the script instead."
)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Report drift and exit non-zero; do not write.",
    )
    args = parser.parse_args()

    settings = get_settings()
    if not settings.budget_spreadsheet_id.strip():
        print("BUDGET_SPREADSHEET_ID is empty — nothing to refresh from.")
        return 1

    known = load_catalog(Manifest.load(settings.documents_dir)).catalog.item_ids
    tiers = _load_pricing_tiers_from_sheets(
        settings.budget_spreadsheet_id,
        credentials_path=settings.google_application_credentials,
    )
    services = _load_service_tiers_from_sheets(
        settings.budget_spreadsheet_id,
        credentials_path=settings.google_application_credentials,
        known_items=known,
    )
    if not tiers or not services:
        print("Sheet returned no tiers or no services; refusing to write an empty card.")
        return 1

    # "Variable" has no row in Pricing_tiers; it is a price by being the absence
    # of one, and the store expects it present.
    prices: dict[str, object] = {key: tiers[key] for key in sorted(tiers)}
    prices["Variable"] = "Variable"

    path = settings.quote_rate_card_path
    fresh = {
        "tiers": prices,
        "services": dict(sorted(services.items())),
        "currency": "GBP",
        "notes": NOTE,
    }

    current = json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}
    changes = _describe_drift(
        dict(current.get("services") or {}),
        services,
        dict(current.get("tiers") or {}),
        prices,
    )
    if not changes:
        print("Rate card already matches the sheet.")
        return 0

    for line in changes:
        print(line)
    if args.check:
        print(f"\n{len(changes)} difference(s). Run without --check to update.")
        return 1

    path.write_text(json.dumps(fresh, indent=2) + "\n", encoding="utf-8")
    print(f"\nWrote {path} — {len(services)} services.")
    return 0


def _describe_drift(
    was: Mapping[str, str],
    now: Mapping[str, str],
    was_tiers: Mapping[str, object],
    now_tiers: Mapping[str, object],
) -> list[str]:
    """Say what changed in the terms someone would ask about: which service, and
    which tier it moved between. A JSON diff would technically answer that and
    practically not."""
    lines = [
        f"  {key}: Tier {was[key]} -> Tier {now[key]}"
        for key in sorted(was.keys() & now.keys())
        if was[key] != now[key]
    ]
    lines += [f"  {key}: added at Tier {now[key]}" for key in sorted(now.keys() - was.keys())]
    lines += [
        f"  {key}: no longer in the sheet (was Tier {was[key]})"
        for key in sorted(was.keys() - now.keys())
    ]
    if was_tiers != now_tiers:
        lines.append(f"  tier prices: {dict(was_tiers)} -> {dict(now_tiers)}")
    return lines


if __name__ == "__main__":
    raise SystemExit(main())
